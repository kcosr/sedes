// Offline installer for versioned Linux/macOS server packages.
// Native compilation and dependency resolution belong to package:server.
import { randomBytes } from "node:crypto";
import {
  chmod,
  copyFile,
  cp,
  lstat,
  mkdir,
  readFile,
  readdir,
  readlink,
  rename,
  rm,
  rmdir,
  symlink,
  writeFile,
} from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { verifyServerRelease } from "./install-server-runtime.mjs";

export const unitMarker = "# Managed by sedes install:server";
const unitOwnerPrefix = "# Installation prefix: ";

class InstallerRefusal extends Error {}

export const usage = `Usage:
  npm run install:server -- --package DIR [--prefix DIR] [--bin-dir DIR] [--no-systemd] [--no-activate] [--force]
  npm run install:server -- --activate VERSION [--prefix DIR] [--bin-dir DIR] [--no-systemd]
  npm run install:server -- --list [--prefix DIR]
  npm run install:server -- --uninstall [--prefix DIR] [--bin-dir DIR] [--purge]

  --package DIR   extracted server release (defaults to this script's package)
  --prefix DIR    installation root (default \${XDG_DATA_HOME:-$HOME/.local/share}/sedes)
  --bin-dir DIR   directory for the sedes launchers (default $HOME/.local/bin)
  --no-systemd    do not write ~/.config/systemd/user/sedes.service
  --no-activate   stage the release without switching 'current' to it
  --force         replace an already installed release of the same version
  --purge         accepted by --uninstall; state and configuration are never removed
`;

const requiredBuildArtifacts = [
  path.join("dist", "server", "index.js"),
  path.join("dist", "cli", "sedes-cli-main.js"),
  path.join("dist", "client", "index.html"),
  "BUILD-INFO.json", "FILES.json", "SHA256SUMS",
  path.join("bin", "sedes"), path.join("bin", "sedes-automation"), path.join("bin", "sedes-server"),
];

const binaryWrappers = [
  { name: "sedes", entry: "dist/cli/sedes-cli-main.js", server: false },
  { name: "sedes-automation", entry: "dist/cli/automation-cli.js", server: false },
  { name: "sedes-server", entry: "dist/server/index.js", server: true },
];

const linkedWrappers = ["sedes", "sedes-automation"];

function token() {
  return randomBytes(6).toString("hex");
}

function wrapperSource({ entry, server }) {
  // $0 is the path the caller used, which is normally the <bin-dir> symlink,
  // so the wrapper resolves itself before locating the release root.
  const lines = [
    "#!/bin/sh",
    'script=$0',
    'while [ -L "$script" ]; do',
    '  base=$(cd -P "$(dirname "$script")" && pwd)',
    '  script=$(readlink "$script")',
    '  case "$script" in /*) ;; *) script="$base/$script" ;; esac',
    'done',
    'root=$(cd -P "$(dirname "$script")/.." && pwd)',
  ];
  if (server) {
    lines.push(`NODE_ENV=production exec node "$root/${entry}" "$@"`);
  } else {
    lines.push(`exec node "$root/${entry}" "$@"`);
  }
  return `${lines.join("\n")}\n`;
}

export async function writeServerWrappers(root) {
  const binDirectory = path.join(root, "bin");
  await mkdir(binDirectory, { recursive: true });
  for (const wrapper of binaryWrappers) {
    const filename = path.join(binDirectory, wrapper.name);
    await writeFile(filename, wrapperSource(wrapper), "utf8");
    await chmod(filename, 0o755);
  }
}

export function unitFileContents(prefix) {
  return `${unitMarker}
${unitOwnerPrefix}${JSON.stringify(prefix)}
# Regenerated by 'npm run install:server'. Remove the marker line above to keep
# local edits; the installer then never rewrites this file.
[Unit]
Description=Sedes server
After=network-online.target

[Service]
Type=simple
ExecStart=${path.join(prefix, "current", "bin", "sedes-server")}
WorkingDirectory=${path.join(prefix, "current")}
Restart=on-failure
KillSignal=SIGTERM
TimeoutStopSec=45
Environment=NODE_ENV=production
# Environment=SEDES_CONFIG_FILE=/absolute/path/to/server.json

[Install]
WantedBy=default.target
`;
}

function parseArguments(argv) {
  const parsed = {
    mode: "install",
    prefix: undefined,
    package: undefined,
    binDir: undefined,
    systemd: true,
    activate: true,
    force: false,
    purge: false,
    version: undefined,
  };
  const modes = [];
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (typeof argument !== "string") return { error: "Invalid argument." };
    const separator = argument.startsWith("--") ? argument.indexOf("=") : -1;
    const flag = separator === -1 ? argument : argument.slice(0, separator);
    const inline = separator === -1 ? undefined : argument.slice(separator + 1);
    let invalid;
    const value = (name) => {
      const raw = inline ?? argv[(index += 1)];
      if (raw === undefined || raw === "" || raw.startsWith("--")) {
        invalid = `${name} requires a value.`;
        return undefined;
      }
      return raw;
    };
    switch (flag) {
      case "--help":
      case "-h":
        return { mode: "help" };
      case "--package":
        parsed.package = value("--package");
        break;
      case "--prefix":
        parsed.prefix = value("--prefix");
        break;
      case "--bin-dir":
        parsed.binDir = value("--bin-dir");
        break;
      case "--no-systemd":
        if (inline !== undefined) invalid = "--no-systemd takes no value.";
        parsed.systemd = false;
        break;
      case "--no-activate":
        if (inline !== undefined) invalid = "--no-activate takes no value.";
        parsed.activate = false;
        break;
      case "--force":
        if (inline !== undefined) invalid = "--force takes no value.";
        parsed.force = true;
        break;
      case "--purge":
        if (inline !== undefined) invalid = "--purge takes no value.";
        parsed.purge = true;
        break;
      case "--list":
        if (inline !== undefined) invalid = "--list takes no value.";
        modes.push("list");
        break;
      case "--uninstall":
        if (inline !== undefined) invalid = "--uninstall takes no value.";
        modes.push("uninstall");
        break;
      case "--activate":
        parsed.version = value("--activate");
        modes.push("activate");
        break;
      default:
        return { error: `Unknown argument: ${argument}` };
    }
    if (invalid !== undefined) return { error: invalid };
  }
  if (modes.length > 1) {
    return { error: `Choose one of --list, --activate, or --uninstall.` };
  }
  parsed.mode = modes[0] ?? "install";
  const rejected = [];
  if (parsed.mode !== "install") {
    if (parsed.force) rejected.push("--force");
    if (parsed.package !== undefined) rejected.push("--package");
    if (!parsed.systemd && parsed.mode !== "activate") rejected.push("--no-systemd");
    if (!parsed.activate) rejected.push("--no-activate");
  }
  if (parsed.mode !== "uninstall" && parsed.purge) rejected.push("--purge");
  if (parsed.mode === "list" && parsed.binDir !== undefined) {
    rejected.push("--bin-dir");
  }
  if (rejected.length > 0) {
    return {
      error: `${rejected.join(", ")} cannot be combined with ${
        parsed.mode === "install" ? "an install" : `--${parsed.mode}`
      }.`,
    };
  }
  return parsed;
}

async function entryKind(target) {
  const metadata = await lstat(target).catch((error) => {
    if (error?.code === "ENOENT") return undefined;
    throw error;
  });
  if (metadata === undefined) return "missing";
  if (metadata.isSymbolicLink()) return "symlink";
  if (metadata.isDirectory()) return "directory";
  return "file";
}

async function activeVersion(prefix) {
  const target = await readlink(path.join(prefix, "current")).catch((error) => {
    if (error?.code === "ENOENT" || error?.code === "EINVAL") return undefined;
    throw error;
  });
  if (target === undefined) return undefined;
  return path.basename(target.replace(/[/\\]+$/u, ""));
}

async function installedReleases(releasesRoot) {
  const entries = await readdir(releasesRoot, { withFileTypes: true }).catch(
    (error) => {
      if (error?.code === "ENOENT") return [];
      throw error;
    },
  );
  return entries
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
    .map((entry) => entry.name)
    .sort((left, right) =>
      left.localeCompare(right, "en", { numeric: true, sensitivity: "base" }),
    );
}

async function checkBinaryOwnership({ prefix, binDir }, name) {
  const link = path.join(binDir, name);
  const target = path.join(prefix, "current", "bin", name);
  const kind = await entryKind(link);
  if (kind === "missing") return false;
  if (kind === "symlink" && path.resolve(binDir, await readlink(link)) === target) return true;
  throw new InstallerRefusal(`Refusing to replace ${link}: it is not a launcher owned by this installation.`);
}

async function linkBinaries(context) {
  const { prefix, binDir, io } = context;
  await mkdir(binDir, { recursive: true });
  for (const name of linkedWrappers) {
    const link = path.join(binDir, name);
    const target = path.join(prefix, "current", "bin", name);
    // Existing owned links already point through current. Never rename over an
    // existing path, including one created after the preflight check.
    if (!(await checkBinaryOwnership(context, name))) await symlink(target, link);
    io.stdout.write(`Linked ${link} -> ${target}\n`);
  }
}

function ownsUnit(contents, prefix) {
  const lines = contents.split("\n");
  return lines.includes(unitMarker) &&
    lines.includes(`${unitOwnerPrefix}${JSON.stringify(prefix)}`);
}

async function preflightActivation(context, systemd) {
  for (const name of linkedWrappers) await checkBinaryOwnership(context, name);
  if (!systemd) return;
  const unitFile = path.join(context.configHome, "systemd", "user", "sedes.service");
  const unit = await readFile(unitFile, "utf8").catch((error) => {
    if (error?.code === "ENOENT") return undefined;
    throw error;
  });
  if (unit?.includes(unitMarker) && !ownsUnit(unit, context.prefix)) {
    throw new InstallerRefusal(`Refusing to replace ${unitFile}: its installation prefix does not match ${context.prefix}.`);
  }
}

function warnMissingPath({ binDir, environment, io }) {
  const entries = (environment.PATH ?? "")
    .split(path.delimiter)
    .filter((entry) => entry !== "")
    .map((entry) => path.resolve(entry));
  if (!entries.includes(path.resolve(binDir))) {
    io.stderr.write(
      `Warning: ${binDir} is not on PATH. Add it to your shell profile to run sedes directly.\n`,
    );
  }
}

async function seedConfiguration({ sourceRoot, configHome, io }) {
  const configDirectory = path.join(configHome, "sedes");
  const configFile = path.join(configDirectory, "server.json");
  if ((await entryKind(configFile)) !== "missing") {
    io.stdout.write(`Kept existing ${configFile}\n`);
    return configFile;
  }
  await mkdir(configDirectory, { recursive: true });
  await copyFile(
    path.join(sourceRoot, "config", "server.example.json"),
    configFile,
  );
  io.stdout.write(
    `Seeded ${configFile} from config/server.example.json; review it before starting the service.\n`,
  );
  return configFile;
}

async function writeUnitFile({ prefix, configHome, io }) {
  const unitDirectory = path.join(configHome, "systemd", "user");
  const unitFile = path.join(unitDirectory, "sedes.service");
  const contents = unitFileContents(prefix);
  const existing = await readFile(unitFile, "utf8").catch((error) => {
    if (error?.code === "ENOENT") return undefined;
    throw error;
  });
  if (existing === undefined) {
    await mkdir(unitDirectory, { recursive: true });
    await writeFile(unitFile, contents, "utf8");
    io.stdout.write(`Wrote ${unitFile}\n`);
    return true;
  }
  if (existing === contents) {
    io.stdout.write(`Unit file ${unitFile} is already up to date.\n`);
    return true;
  }
  if (!ownsUnit(existing, prefix)) {
    io.stderr.write(
      `Warning: ${unitFile} is not installer-managed (no '${unitMarker}' line); left unchanged.\n`,
    );
    return false;
  }
  await writeFile(unitFile, contents, "utf8");
  io.stdout.write(`Updated ${unitFile}\n`);
  return true;
}

function printNextSteps({ io, upgraded, wroteUnit, systemd }) {
  io.stdout.write("\nNext steps:\n");
  if (systemd && wroteUnit) {
    io.stdout.write("  systemctl --user daemon-reload\n");
    io.stdout.write(
      upgraded
        ? "  systemctl --user restart sedes.service\n"
        : "  systemctl --user enable --now sedes.service\n",
    );
  } else {
    io.stdout.write(
      "  (no unit file managed here; start the service the way this host already does)\n",
    );
  }
  io.stdout.write(
    "Back up the complete state directory (APP_STATE_DIR, by default\n" +
      "${XDG_STATE_HOME:-$HOME/.local/state}/sedes) before every upgrade: an older\n" +
      "release refuses a database a newer release has migrated, so a rollback needs\n" +
      "its matching pre-upgrade backup.\n",
  );
}

async function stageRelease(context) {
  const {
    sourceRoot,
    prefix,
    io,
    options,
    parsed,
  } = context;

  for (const artifact of requiredBuildArtifacts) {
    if ((await entryKind(path.join(sourceRoot, artifact))) !== "file") {
      io.stderr.write(
        `Missing ${artifact} in ${sourceRoot}; create a release with \`npm run package:server -- --target <target>\` first.\n`,
      );
      return 1;
    }
  }

  const manifest = JSON.parse(
    await readFile(path.join(sourceRoot, "package.json"), "utf8"),
  );
  const version = manifest.version;
  if (typeof version !== "string" || !/^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/u.test(version)) {
    io.stderr.write(`${sourceRoot}/package.json has no version.\n`);
    return 1;
  }

  const releasesRoot = path.join(prefix, "releases");
  const releaseDirectory = path.join(releasesRoot, version);
  const active = await activeVersion(prefix);
  if ((await entryKind(releaseDirectory)) !== "missing") {
    if (active === version) {
      io.stderr.write(
        `${version} is the active release (${path.join(prefix, "current")}); refusing to replace it.\n` +
          `Activate another release first: npm run install:server -- --activate <version>\n`,
      );
      return 1;
    }
    if (!parsed.force) {
      io.stderr.write(
        `${releaseDirectory} already exists; pass --force to replace it.\n`,
      );
      return 1;
    }
  }

  const stagingDirectory = path.join(
    releasesRoot,
    `.staging-${version}-${token()}`,
  );
  await mkdir(stagingDirectory, { recursive: true });
  io.stdout.write(`Staging sedes ${version} in ${stagingDirectory}\n`);

  let staged = false;
  try {
    await cp(sourceRoot, stagingDirectory, { recursive: true, verbatimSymlinks: true });
    io.stdout.write("Verifying copied server package offline before activation\n");
    const info = await verifyRelease(context, stagingDirectory, false);

    await writeFile(
      path.join(stagingDirectory, "RELEASE.json"),
      `${JSON.stringify(
        {
          version,
          commit: info.source.commit,
          target: info.target.label,
          systemd: parsed.systemd,
          installedAt: (options.now?.() ?? new Date()).toISOString(),
          node: options.nodeVersion ?? process.version,
        },
        null,
        2,
      )}\n`,
      "utf8",
    );

    let replaced;
    if ((await entryKind(releaseDirectory)) !== "missing") {
      replaced = path.join(releasesRoot, `.replaced-${version}-${token()}`);
      await rename(releaseDirectory, replaced);
    }
    try {
      await rename(stagingDirectory, releaseDirectory);
    } catch (error) {
      if (replaced !== undefined) await rename(replaced, releaseDirectory);
      throw error;
    }
    staged = true;
    if (replaced !== undefined) {
      await rm(replaced, { force: true, recursive: true });
    }
  } finally {
    if (!staged) await rm(stagingDirectory, { force: true, recursive: true });
  }
  io.stdout.write(`Installed release ${releaseDirectory}\n`);

  if (!parsed.activate) {
    io.stdout.write(
      `Staged only; ${path.join(prefix, "current")} still points at ${active ?? "nothing"}.\n` +
        `Activate it with: npm run install:server -- --activate ${version}\n`,
    );
    return 0;
  }

  return await finishActivation(context, version, parsed.systemd);
}

async function verifyRelease(context, root, installed) {
  const { options, environment } = context;
  return await (options.verifyPackage ?? verifyServerRelease)(root, environment, {
    installed,
    platform: options.platform ?? process.platform,
    arch: options.arch ?? process.arch,
    nodeVersion: options.nodeVersion ?? process.version,
    nodeAbi: options.nodeAbi ?? process.versions.modules,
  });
}

async function finishActivation(context, version, systemd) {
  const { prefix, binDir, environment, configHome, io } = context;
  const active = await activeVersion(prefix);
  await preflightActivation(context, systemd);
  await linkBinaries(context);
  warnMissingPath({ binDir, environment, io });
  await seedConfiguration({
    sourceRoot: path.join(prefix, "releases", version), configHome, io,
  });
  const wroteUnit = systemd ? await writeUnitFile({ prefix, configHome, io }) : false;
  if (!systemd) io.stdout.write("Skipped the systemd unit file (--no-systemd).\n");
  // Make the candidate current only after the prerequisites are ready.
  await swapCurrent(prefix, version);
  io.stdout.write(`Activated ${version} (${path.join(prefix, "current")} -> releases/${version})\n`);
  printNextSteps({ io, upgraded: active !== undefined, wroteUnit, systemd });
  return 0;
}

async function swapCurrent(prefix, version) {
  await mkdir(prefix, { recursive: true });
  const temporary = path.join(prefix, `current.tmp-${token()}`);
  await rm(temporary, { force: true });
  await symlink(path.join("releases", version), temporary);
  await rename(temporary, path.join(prefix, "current"));
}

async function activateRelease(context) {
  const { prefix, io, parsed } = context;
  const version = parsed.version;
  if (!/^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/u.test(version)) throw new InstallerRefusal("Invalid release version.");
  const releaseDirectory = path.join(prefix, "releases", version);
  if ((await entryKind(releaseDirectory)) === "missing") {
    io.stderr.write(
      `No installed release ${version} in ${path.join(prefix, "releases")}.\n` +
        `List installed releases with: npm run install:server -- --list\n`,
    );
    return 1;
  }
  const release = JSON.parse(await readFile(path.join(releaseDirectory, "RELEASE.json"), "utf8"));
  if (release.version !== version || typeof release.systemd !== "boolean") {
    throw new InstallerRefusal(`Invalid release metadata for ${version}.`);
  }
  await verifyRelease(context, releaseDirectory, true);
  const systemd = parsed.systemd && release.systemd;
  if ((await activeVersion(prefix)) === version) {
    io.stdout.write(`${version} is already the active release; checking installation setup.\n`);
  }
  return await finishActivation(context, version, systemd);
}

async function listInstalledReleases(context) {
  const { prefix, io } = context;
  const releasesRoot = path.join(prefix, "releases");
  const releases = await installedReleases(releasesRoot);
  if (releases.length === 0) {
    io.stdout.write(`No releases installed in ${releasesRoot}.\n`);
    return 0;
  }
  const active = await activeVersion(prefix);
  io.stdout.write(`Releases in ${releasesRoot}:\n`);
  for (const release of releases) {
    io.stdout.write(
      release === active ? `* ${release} (active)\n` : `  ${release}\n`,
    );
  }
  if (active !== undefined && !releases.includes(active)) {
    io.stderr.write(
      `Warning: ${path.join(prefix, "current")} points at ${active}, which is not installed.\n`,
    );
  }
  return 0;
}

async function uninstall(context) {
  const { prefix, binDir, configHome, io } = context;
  let removedUnit = false;
  for (const name of linkedWrappers) {
    const link = path.join(binDir, name);
    const kind = await entryKind(link);
    if (kind === "missing") continue;
    if (kind !== "symlink") {
      io.stderr.write(`Warning: ${link} is not a symlink; left in place.\n`);
      continue;
    }
    const target = path.resolve(binDir, await readlink(link));
    if (target !== path.join(prefix, "current", "bin", name)) {
      io.stderr.write(
        `Warning: ${link} points at ${target}, not this installation; left in place.\n`,
      );
      continue;
    }
    await rm(link, { force: true });
    io.stdout.write(`Removed ${link}\n`);
  }

  const unitFile = path.join(configHome, "systemd", "user", "sedes.service");
  const unit = await readFile(unitFile, "utf8").catch((error) => {
    if (error?.code === "ENOENT") return undefined;
    throw error;
  });
  if (unit === undefined) {
    // Nothing to remove.
  } else if (ownsUnit(unit, prefix)) {
    await rm(unitFile, { force: true });
    removedUnit = true;
    io.stdout.write(`Removed ${unitFile}\n`);
  } else {
    io.stderr.write(
      `Warning: ${unitFile} is not installer-managed by this installation; left in place.\n`,
    );
  }

  const current = path.join(prefix, "current");
  if ((await entryKind(current)) !== "missing") {
    await rm(current, { force: true, recursive: true });
    io.stdout.write(`Removed ${current}\n`);
  }
  const releasesRoot = path.join(prefix, "releases");
  if ((await entryKind(releasesRoot)) !== "missing") {
    await rm(releasesRoot, { force: true, recursive: true });
    io.stdout.write(`Removed ${releasesRoot}\n`);
  }
  await rmdir(prefix).catch(() => undefined);

  io.stdout.write(
    "\nThis script never removes application state or configuration, with or\n" +
      `without --purge: ${path.join(configHome, "sedes", "server.json")} and the state\n` +
      "directory (APP_STATE_DIR, by default ${XDG_STATE_HOME:-$HOME/.local/state}/sedes)\n" +
      "are untouched. Remove them yourself, after a backup, if you really want them gone.\n",
  );
  if (removedUnit) io.stdout.write(
    "\nIf the service was enabled, also run:\n" +
      "  systemctl --user disable --now sedes.service\n" +
      "  systemctl --user daemon-reload\n",
  );
  return 0;
}

async function withInstallationLocks(context, operation) {
  const { prefix, binDir, configHome, parsed } = context;
  const paths = [path.join(prefix, ".installer.lock")];
  if (parsed.mode !== "install" || parsed.activate) {
    // Different prefixes can still share launchers and a user service. Lock
    // those resources too, so ownership checks remain valid through mutation.
    paths.push(path.join(binDir, ".sedes-installer.lock"));
    paths.push(path.join(configHome, "sedes", ".installer.lock"));
  }
  const acquired = [];
  try {
    for (const lock of [...new Set(paths)].sort()) {
      await mkdir(path.dirname(lock), { recursive: true });
      try {
        await mkdir(lock, { mode: 0o700 });
      } catch (error) {
        if (error?.code === "EEXIST") {
          throw new InstallerRefusal(`Installer busy: ${lock}. If a previous installer crashed, verify its recorded process has stopped before removing this lock directory.`);
        }
        throw error;
      }
      acquired.push(lock);
      await writeFile(path.join(lock, "owner.json"), `${JSON.stringify({ pid: process.pid, prefix })}\n`, { mode: 0o600 });
    }
    return await operation();
  } finally {
    for (const lock of acquired.reverse()) {
      await rm(path.join(lock, "owner.json"), { force: true });
      await rmdir(lock);
    }
    if (parsed.mode === "uninstall") await rmdir(prefix).catch(() => undefined);
  }
}

export async function installServer(options = {}) {
  const io = options.io ?? { stdout: process.stdout, stderr: process.stderr };
  const parsed = parseArguments(options.argv ?? []);
  if (parsed.error !== undefined) {
    io.stderr.write(`${parsed.error}\n\n${usage}`);
    return 2;
  }
  if (parsed.mode === "help") {
    io.stdout.write(usage);
    return 0;
  }

  const platform = options.platform ?? process.platform;
  if (!["linux", "darwin"].includes(platform) || (platform !== "linux" && parsed.systemd && ["install", "activate"].includes(parsed.mode))) {
    io.stderr.write(
      `install:server installs a systemd user service and supports Linux only; this host reports ${platform}.\n` +
        "On macOS pass --no-systemd and manage the server process separately.\n",
    );
    return 1;
  }

  const environment = options.environment ?? process.env;
  const homeDirectory =
    options.homeDirectory ?? environment.HOME ?? os.homedir();
  const dataHome =
    environment.XDG_DATA_HOME !== undefined &&
    path.isAbsolute(environment.XDG_DATA_HOME)
      ? environment.XDG_DATA_HOME
      : path.join(homeDirectory, ".local", "share");
  const configHome =
    environment.XDG_CONFIG_HOME !== undefined &&
    path.isAbsolute(environment.XDG_CONFIG_HOME)
      ? environment.XDG_CONFIG_HOME
      : path.join(homeDirectory, ".config");
  const prefix = path.resolve(
    parsed.prefix ?? options.prefix ?? path.join(dataHome, "sedes"),
  );
  const binDir = path.resolve(
    parsed.binDir ??
      options.binDir ??
      path.join(homeDirectory, ".local", "bin"),
  );
  const sourceRoot = path.resolve(
    parsed.package ?? options.packageRoot ??
      path.dirname(path.dirname(fileURLToPath(import.meta.url))),
  );
  const context = {
    sourceRoot,
    prefix,
    binDir,
    configHome,
    environment,
    homeDirectory,
    io,
    options,
    parsed,
  };

  if (parsed.mode === "list") return await listInstalledReleases(context);
  try {
    return await withInstallationLocks(context, async () => {
      switch (parsed.mode) {
        case "activate": return await activateRelease(context);
        case "uninstall": return await uninstall(context);
        default: return await stageRelease(context);
      }
    });
  } catch (error) {
    io.stderr.write(`${error instanceof Error ? error.message : "Installation failed."}\n`);
    return 1;
  }
}
